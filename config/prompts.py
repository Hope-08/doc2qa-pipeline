TEXT_QA_PROMPT = """\
你是专业的知识库 QA 生成专家。你的任务是从文本中提取**真实用户在使用知识库时会实际提问**的问题。

【严格禁止生成以下类型的问题，否则输出无效】
1. 元文本分析题：问题中含"这段文本"、"这段内容"、"可以判断"、"为什么这段话"——没有真实用户会问这些
2. 同义反复题：答案只是把问题换个说法重复，如问"X是什么意思"→答"X指的是X"
3. 不完整信息题：如果文本某句话明显被截断，不要基于该残缺信息提问
4. 纯数据罗列题：内容只是日期、价格数字列表，不含实际知识点，直接跳过不生成

【好问题的衡量标准】
- 用户不看原文，凭问题本身就能理解在问什么
- 答案让读者学到具体有用的知识（地点特色、操作步骤、注意事项、具体建议等）
- 问题和答案都不依赖"文中说"、"根据文本"之类的指代

【反面示例（不要生成）】
× "为什么可以判断这段文本是一组日期信息？"
× "文中提到的'纯玩不购物'是什么意思？" → 若答案只是"指行程中不安排购物"，则是同义反复
× "为什么文中会说乌鲁木齐位于亚洲的中心？" → 答案："因为文本直接指出乌鲁木齐位于亚洲中心"，循环论证

【正面示例（应生成此类问题）】
✓ "乌鲁木齐有哪些值得一去的景点？"
✓ "参加这个新疆团队游，最少需要几人才能成行？"
✓ "去新疆博物馆需要购票吗？"

---

基于以下文本生成 3 个高质量问答对，类型分别为：
1. definition（定义类）：询问某个具体事物/地点/政策的实质内容，答案要包含具体信息
2. reasoning（推理类）：询问某个安排或建议背后的实际原因，答案要说明真正的理由
3. procedure（流程类）：询问如何完成某个具体操作或行程，答案要给出可操作的步骤

如果文本中没有足够信息支撑某种类型，可以将该类型替换为更合适的类型，但必须保证 3 个问题都有实质内容。
如果整段文本不含有价值的领域知识（如纯粹是日期列表、联系方式独立片段），返回空数组 []。

文本内容：
{context}

输出格式（严格 JSON，不要有多余文字）：
[
  {{"question": "...", "answer": "...", "type": "definition"}},
  {{"question": "...", "answer": "...", "type": "reasoning"}},
  {{"question": "...", "answer": "...", "type": "procedure"}}
]"""

