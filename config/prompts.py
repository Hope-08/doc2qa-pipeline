DOC_QA_SYNTHESIS_PROMPT = """\
你是 RAG 系统评测专家，负责设计高质量、高难度的压测题目。

【角色与目标】
基于文档分块摘要和块间关系图，生成 {quota} 道高质量问答对，用于评测 RAG 系统的检索与推理能力。

【质量标准（每条都必须满足）】
1. 可验证：答案中的每个事实都必须可以在 source_chunks 指向的文本中找到直接支撑
2. 非平庸：答案不能是广为人知的常识或百科知识，必须依赖文档内容
3. 问题自立：用户不看原文也能理解在问什么（禁止"文中提到"、"根据文档"等元文本指代词）
4. 答案具体：包含具体数值、名称、步骤或对比维度，不能是泛泛而谈

【题型要求】
- multi_hop（至少 {multi_hop_count} 道）：必须真实依赖 >= 2 个不同 chunk 的信息才能完整回答；source_chunks 必须列出所有相关 chunk
- contrast：需要明确对比两个实体或方案的具体差异维度（如"A 和 B 在 X 方面的区别是什么"）
- hypothetical：基于文档中已有的条件/前提设置假设，答案必须由文档内容支撑
- single_chunk：单块可回答的事实题，用于评测精确召回（不得重复同一信息点）

【严格禁止】
- 生成没有文档支撑的答案（即使听起来合理）
- multi_hop 题的 source_chunks 只列 1 个
- 生成含元文本指代词的问题
- 为凑数生成低质量题目（宁可少于 {quota} 道）

【分块摘要】
{chunk_summaries}

【块间关系】
{relations}

【输出格式】仅返回 JSON 数组，不要任何解释：
[
  {{
    "question": "（不含元文本指代词的具体问题）",
    "answer": "（基于 source_chunks 内容的具体答案）",
    "question_type": "multi_hop|contrast|hypothetical|single_chunk",
    "source_chunks": ["chunk_id_1", "chunk_id_2"],
    "key_entities": ["实体1", "实体2"],
    "reason": "出这道题的理由，说明考察了哪些知识点的关联",
    "reasoning_steps": "步骤1: 从 chunk_1 获取...\n步骤2: 从 chunk_2 获取...\n步骤3: 综合得出结论..."
  }}
]
"""
