TEXT_QA_PROMPT = """\
你是专业的知识库 QA 生成专家。你的任务是从文本中提取**真实用户在使用知识库时会实际提问**的问题。

【角色与目标】
为后续 RAG 系统训练/评测生成高信噪比的问答对。问题必须让用户在不看原文的情况下也能清晰理解在问什么；答案必须让读者学到具体可用的知识。

【明确禁止生成以下类型，违反则整条输出无效】
1. 元文本分析题：问题或答案中含"这段文本"、"这段内容"、"根据材料"、"文中提到"、"文章指出"、"从文章可以看出"——没有真实用户会问这些
2. 同义反复题：答案只是把问题换个说法复述，不含任何新信息
3. 循环论证题：答案是"因为文本说了，所以就是"这类逻辑
4. 截断信息题：基于明显被截断/残缺的句子提问
5. 纯数据罗列题：内容只是日期列表、价格列表、电话号码，不含实质知识点

【质量标准（每条都要满足）】
- 问题自立：用户不看原文也能理解在问什么
- 答案实质：包含具体地点、步骤、数值、注意事项等可操作信息
- 答案可验证：答案中的事实可以在文本中直接找到支撑

【好/坏示例】
× 坏："文中提到的'纯玩不购物'是什么意思？" → 元文本指代
× 坏："为什么这段文字会提到乌鲁木齐位于亚洲的中心？" → 元文本分析
× 坏："深度学习是什么？" → "深度学习是深度学习。" → 同义反复
✓ 好："乌鲁木齐有哪些值得一去的景点？" → 具体知识点
✓ 好："参加这个团队游最少需要几人才能成行？" → 可操作信息
✓ 好："使用该系统提交申请后多久会收到审批结果？" → 具体时效信息

【输出规则】
- 生成 3 个问答对，类型依次为：definition（定义/事实查询）、reasoning（原因/机制）、procedure（操作/流程）
- 若文本中没有足够信息支撑某种类型，用其他合适类型替代（保证 3 个都有实质内容）
- 若整段文本不含有价值的领域知识（如纯日期、联系方式、目录碎片），直接返回 []，不要强行生成
- 宁可少生成（甚至 []），也不要生成低质量问答

文本内容：
{context}

输出格式（严格 JSON 数组，不要有任何解释或多余文字）：
[
  {{
    "question": "...",
    "answer": "...",
    "type": "definition",
    "reason": "出这道题的理由，说明该问题考察了哪个知识点或逻辑关系",
    "reasoning_steps": "步骤1: ...\n步骤2: ...\n步骤3: 得出结论..."
  }},
  ...
]"""

